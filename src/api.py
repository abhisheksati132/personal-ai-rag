@app.post(
    "/auth/login",
    response_model=LoginResponse,
    summary="Login to private brain instance",
)
def login(request: LoginRequest, raw_request: Request) -> LoginResponse:
    """Validate password and issue an authenticated session bearer token.
    Throttles failed login attempts per client IP (lockout after 5 failures in 60s).
    """
    client_ip = get_client_ip(raw_request)

    is_locked, retry_after = login_limiter.is_locked(client_ip)
    if is_locked:
        logger.warning(f"Login rate limit lockout for IP: {client_ip} (retry_after={retry_after}s)")
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail=f"Too many failed login attempts. Please wait {retry_after} seconds before retrying.",
            headers={"Retry-After": str(retry_after)},
        )

    if is_auth_enabled() and not verify_password(request.password):
        is_now_locked, lockout_sec = login_limiter.record_failure(client_ip)
        if is_now_locked:
            logger.warning(f"Login triggered lockout for IP: {client_ip} (lockout={lockout_sec}s)")
            raise HTTPException(
                status_code=status.HTTP_429_TOO_MANY_REQUESTS,
                detail=f"Too many failed login attempts. Please wait {lockout_sec} seconds before retrying.",
                headers={"Retry-After": str(lockout_sec)},
            )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid password",
        )

    login_limiter.record_success(client_ip)
    token_data = create_access_token()
    return LoginResponse(**token_data)


@app.get(
    "/auth/status",
    response_model=AuthStatusResponse,
    summary="Check if auth is enabled and if current token is valid",
)
def auth_status(authorization: Optional[str] = Header(None)) -> AuthStatusResponse:
    """Return whether authentication is enabled and whether the client token is valid."""
    if not is_auth_enabled():
        return AuthStatusResponse(auth_enabled=False, authenticated=True)

    is_valid = False
    if authorization and authorization.startswith("Bearer "):
        token = authorization[7:].strip()
        is_valid = verify_token(token)

    return AuthStatusResponse(auth_enabled=True, authenticated=is_valid)


