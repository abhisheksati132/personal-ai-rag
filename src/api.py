# --- Request & Response Schemas ---

class QueryRequest(BaseModel):
    question: str = Field(..., min_length=1, description="Natural language question to ask your brain")
    top_k: Optional[int] = Field(None, ge=1, le=20, description="Max chunks to retrieve")
    min_score: Optional[float] = Field(None, ge=0.0, le=1.0, description="Relevance score threshold")
    provider: Optional[Literal["local", "cloud"]] = Field(
        default="local",
        description="LLM provider to use for synthesis: 'local' (Ollama) or 'cloud' (Groq)",
    )

    @field_validator("question")
    @classmethod
    def validate_question_not_blank(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Question cannot be empty or only whitespace")
        return stripped


class SourceInfo(BaseModel):
    file: str = Field(..., description="Source file name")
    chunk_index: int = Field(..., description="Position index of the chunk")
    score: float = Field(..., description="Cosine similarity score")


class QueryResponse(BaseModel):
    answer: str = Field(..., description="Grounded answer generated by LLM")
    sources: list[SourceInfo] = Field(default_factory=list, description="Source documents cited in answer")
    provider: str = Field(default="local", description="LLM provider used for generation ('local' or 'cloud')")
    model: str = Field(default="llama3.2", description="Model name used for synthesis")


class HealthResponse(BaseModel):
    status: str
    ollama_connected: bool
    groq_configured: bool
    embedding_model: str
    llm_model: str
    groq_model: str
    indexed_files: int
    total_vectors: int


